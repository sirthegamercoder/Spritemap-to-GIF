_INVALID_CHARS = '<>:"/\\|?*'
_RESERVED_NAMES = {
    "CON",
    "PRN",
    "AUX",
    "NUL",
    *(f"COM{i}" for i in range(1, 10)),
    *(f"LPT{i}" for i in range(1, 10)),
}


def sanitize_filename(name: str) -> str:
    cleaned = "".join("_" if ch in _INVALID_CHARS else ch for ch in name)
    cleaned = cleaned.strip().rstrip(". ")
    if not cleaned:
        return "unnamed"
    if cleaned.upper().split(".")[0] in _RESERVED_NAMES:
        cleaned = f"_{cleaned}"
    return cleaned


class GifWriter:
    @staticmethod
    def save(
        frames: list,
        gif_path: Path,
        duration: int,
        loop: int,
        disposal: int,
    ) -> None:
        if not frames:
            return
        first, *rest = frames
        first.save(
            gif_path,
            save_all=True,
            append_images=rest,
            duration=duration,
            loop=loop,
            disposal=disposal,
            comment="GIF Generated by: Spritemap to GIF",
        )


def validate_animation_json(path: Path) -> None:
    try:
        with path.open("r", encoding="utf-8-sig") as fh:
            data = json.load(fh)
    except json.JSONDecodeError as exc:
        raise ValueError(f"{path.name} is not valid JSON: {exc}") from exc
    if not isinstance(data, dict):
        raise ValueError(f"{path.name} must contain a JSON object at the top level.")


class DropLineEdit(QLineEdit):
    def __init__(self, file_mode: str = "file", extensions: tuple = (), parent=None):
        super().__init__(parent)
        self.file_mode = file_mode
        self.extensions = extensions
        self.setAcceptDrops(True)

    def dragEnterEvent(self, event):
        if event.mimeData().hasUrls():
            urls = event.mimeData().urls()
            if len(urls) == 1 and self._is_valid_path(urls[0].toLocalFile()):
                event.acceptProposedAction()
                self._set_drag_style(True)
                return
        event.ignore()

    def dragLeaveEvent(self, event):
        self._set_drag_style(False)
        super().dragLeaveEvent(event)

    def dropEvent(self, event):
        self._set_drag_style(False)
        if event.mimeData().hasUrls():
            urls = event.mimeData().urls()
            if len(urls) == 1:
                path = urls[0].toLocalFile()
                if self._is_valid_path(path):
                    self.setText(path)
                    event.acceptProposedAction()
                    return
        event.ignore()

    def _is_valid_path(self, path: str) -> bool:
        if not path:
            return False
        p = Path(path)
        if self.file_mode == "folder":
            return p.is_dir()
        if not p.is_file():
            return False
        if self.extensions and p.suffix.lower() not in self.extensions:
            return False
        return True

    def _set_drag_style(self, active: bool):
        self.setProperty("dragActive", active)
        self.style().unpolish(self)
        self.style().polish(self)


class ExportWorker(QThread):
    progress = Signal(int, int, str)
    log = Signal(str)
    finished_export = Signal(str)
    error = Signal(str)

    def __init__(
        self,
        animation_path: str,
        spritemap_json_path: str,
        atlas_image_path: str,
        output_dir: str,
        duration: int,
        loop: int,
        disposal: int,
        filter_single_frame: bool,
        filter_unused_symbols: bool,
        root_animation_only: bool,
    ):
        super().__init__()
        self.animation_path = animation_path
        self.spritemap_json_path = spritemap_json_path
        self.atlas_image_path = atlas_image_path
        self.output_dir = output_dir
        self.duration = duration
        self.loop = loop
        self.disposal = disposal
        self.filter_single_frame = filter_single_frame
        self.filter_unused_symbols = filter_unused_symbols
        self.root_animation_only = root_animation_only
        self._cancel = False

    def cancel(self):
        self._cancel = True

    def run(self):
        renderer = None
        try:
            try:
                validate_animation_json(Path(self.animation_path))
                validate_animation_json(Path(self.spritemap_json_path))
            except ValueError as exc:
                self.error.emit(str(exc))
                return

            self.log.emit("Loading animation document...")
            renderer = AdobeSpritemapRenderer(
                animation_path=self.animation_path,
                spritemap_json_path=self.spritemap_json_path,
                atlas_image_path=self.atlas_image_path,
                filter_single_frame=self.filter_single_frame,
                filter_unused_symbols=self.filter_unused_symbols,
                root_animation_only=self.root_animation_only,
            )

            root_name = renderer.get_root_animation_name() or "spritemap"
            output_path = Path(self.output_dir) / sanitize_filename(root_name)
            output_path.mkdir(parents=True, exist_ok=True)
            self.log.emit(f"Created output folder: {output_path}")

            animations = list(renderer.iter_animations())
            total = len(animations)
            if total == 0:
                self.error.emit("No animations found to export.")
                return

            exported = 0
            failures = 0
            for index, (name, frame_iterator) in enumerate(animations, start=1):
                if self._cancel:
                    self.log.emit("Export cancelled by user.")
                    return

                safe_name = sanitize_filename(name)
                self.progress.emit(index, total, safe_name)
                self.log.emit(f"Rendering '{safe_name}'...")

                try:
                    frames = []
                    for _, frame_image, _ in frame_iterator:
                        if self._cancel:
                            self.log.emit("Export cancelled by user.")
                            for f in frames:
                                f.close()
                            return
                        frames.append(frame_image)

                    if not frames:
                        self.log.emit(f"  Skipping '{safe_name}' (no frames).")
                        continue

                    gif_path = output_path / f"{safe_name}.gif"
                    GifWriter.save(
                        frames,
                        gif_path,
                        duration=self.duration,
                        loop=self.loop,
                        disposal=self.disposal,
                    )
                    for frame in frames:
                        frame.close()

                    exported += 1
                    self.log.emit(f"  Saved: {gif_path.name}")
                except Exception as exc:
                    failures += 1
                    self.log.emit(f"  ERROR on '{safe_name}': {exc}")

            summary = f"Export complete. {exported} GIF(s) saved to:\n{output_path}"
            if failures:
                summary += f"\n\n{failures} animation(s) failed — see log."
            self.finished_export.emit(summary)
        except Exception as exc:
            self.error.emit(str(exc))
        finally:
            if renderer is not None:
                renderer.close()


class MainWindow(QMainWindow):
    def __init__(self):
        super().__init__()
        self.setWindowTitle("Spritemap to GIF")
        self.setWindowIcon(QIcon(":ui/icon.ico"))
        self.setMinimumSize(750, 770)
        self.resize(750, 770)
        self.worker = None
        self._last_output_dir = None

        self._build_ui()
        self._apply_styles()
        self._center_window()

    def _center_window(self):
        screen = QApplication.primaryScreen().availableGeometry()
        window_frame = self.frameGeometry()
        window_frame.moveCenter(screen.center())
        self.move(window_frame.topLeft())

